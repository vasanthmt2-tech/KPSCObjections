# Scripts the tables and stored procedures of the objections database into
# Database\schema.sql so the schema is versioned alongside the code.
# Uses Windows authentication; no data is exported.
param(
    [string]$Server = $env:COMPUTERNAME,
    [string]$Database = 'KPSC_OBJECTIONS',
    [string]$OutFile = (Join-Path $PSScriptRoot 'schema.sql')
)

$ErrorActionPreference = 'Stop'
[void][System.Reflection.Assembly]::LoadWithPartialName('Microsoft.SqlServer.Smo')

$srv = New-Object Microsoft.SqlServer.Management.Smo.Server $Server
$db = $srv.Databases[$Database]
if (-not $db) { throw "Database '$Database' not found on '$Server'." }

$scripter = New-Object Microsoft.SqlServer.Management.Smo.Scripter $srv
$o = $scripter.Options
$o.ScriptData = $false
$o.DriAll = $true
$o.Indexes = $true
$o.Triggers = $true
$o.IncludeHeaders = $false
$o.SchemaQualify = $true
$o.AnsiPadding = $false
$o.NoCollation = $true
$o.ScriptBatchTerminator = $true

$tables = @($db.Tables | Where-Object { -not $_.IsSystemObject } | Sort-Object Name)
$procedures = @($db.StoredProcedures | Where-Object { -not $_.IsSystemObject } | Sort-Object Name)
$objects = $tables + $procedures

$sb = New-Object System.Text.StringBuilder
[void]$sb.AppendLine("-- Schema of $Database. Generated by Database\Export-Schema.ps1; do not edit by hand.")
function Add-Script($title, $lines) {
    [void]$sb.AppendLine()
    [void]$sb.AppendLine("-- $title")
    foreach ($line in $lines) {
        [void]$sb.AppendLine($line)
        [void]$sb.AppendLine('GO')
    }
}

# Tables first without their foreign keys, then the foreign keys, so the
# script runs on an empty database whatever order the tables reference
# each other in (tables are in name order).
$o.DriAll = $false
$o.DriPrimaryKey = $true
$o.DriUniqueKeys = $true
$o.DriChecks = $true
$o.DriDefaults = $true
$o.DriIndexes = $true
$o.DriClustered = $true
$o.DriNonClustered = $true
$o.DriForeignKeys = $false
foreach ($t in $tables) { Add-Script "Table: $($t.Schema).$($t.Name)" $scripter.Script($t) }

$fkOptions = New-Object Microsoft.SqlServer.Management.Smo.ScriptingOptions
$fkOptions.SchemaQualify = $true
$fkOptions.SchemaQualifyForeignKeysReferences = $true
foreach ($t in $tables) {
    foreach ($fk in ($t.ForeignKeys | Sort-Object Name)) {
        Add-Script "Foreign key: $($t.Schema).$($t.Name).$($fk.Name)" $fk.Script($fkOptions)
    }
}

foreach ($p in $procedures) { Add-Script "StoredProcedure: $($p.Schema).$($p.Name)" $scripter.Script($p) }

[System.IO.File]::WriteAllText($OutFile, $sb.ToString(), (New-Object System.Text.UTF8Encoding $false))
Write-Output "Wrote $($objects.Count) objects to $OutFile"
